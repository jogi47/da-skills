# Prints the account id this setup uses: config, then CLIENT_PAGE_ACCOUNT_ID, then the token's only account.
# Returns 2 (after listing them on stderr) when the token sees several accounts.
find_account() {
  local a out n
  a="$(conf_get account_id)"; [[ -n "$a" ]] && { printf '%s' "$a"; return 0; }
  [[ -n "${CLIENT_PAGE_ACCOUNT_ID:-}" ]] && { printf '%s' "$CLIENT_PAGE_ACCOUNT_ID"; return 0; }
  out="$(cf_try GET "/accounts?per_page=50")" || return 1
  n="$(jq '.result | length' <<<"$out")"
  if [[ "$n" -eq 1 ]]; then jq -r '.result[0].id' <<<"$out"; return 0; fi
  if [[ "$n" -gt 1 ]]; then jq -r '.result[] | "        \(.id)  \(.name)"' <<<"$out" >&2; return 2; fi
  return 1
}

workers_dev_subdomain() { # ACCOUNT_ID → the account's <name> in <name>.workers.dev, or nothing
  local out; out="$(cf_try GET "/accounts/$1/workers/subdomain")" || return 0
  jq -r '.result.subdomain // empty' <<<"$out"
}

