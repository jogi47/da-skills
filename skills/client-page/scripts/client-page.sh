#!/usr/bin/env bash
# client-page: publish pages with saved answers to https://<host>/<uuid> on Cloudflare (Worker + D1).
#
# Needs no Cloudflare CLI (no wrangler, no cloudflared): it calls Cloudflare's REST API with curl.
# Start with `doctor`: it checks every prerequisite and prints the next step for anything missing.
#
# Secrets never appear on a command line; they reach curl on stdin (-K -). They are kept in macOS
# Keychain (account "client-page"), or, where there is no Keychain, in mode-600 files in the config dir:
#   client-page-cloudflare-token  the Cloudflare API token the user creates (doctor explains how)
#   client-page-admin-token       generated by `setup`; the Worker's ADMIN_TOKEN secret
# Non-secret settings (host, account, zone and database ids) live in ~/.config/client-page/config.json.
set -euo pipefail

SKILL_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONF_DIR="${CLIENT_PAGE_CONFIG_DIR:-$HOME/.config/client-page}"
CONF="$CONF_DIR/config.json"
NAME_DEFAULT="client-page"          # Worker script name and D1 database name
COMPAT_DATE="2026-09-01"
KC_ACCOUNT="client-page"
KC_CF="client-page-cloudflare-token"
KC_ADMIN="client-page-admin-token"
API="https://api.cloudflare.com/client/v4"

die() { echo "client-page: $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null 2>&1 || die "needs '$1' on PATH; run: $0 doctor"; }
have() { command -v "$1" >/dev/null 2>&1; }

# ---------- secrets ----------

use_keychain() { [[ "${CLIENT_PAGE_SECRET_STORE:-}" != file ]] && have security; }
secret_file() { printf '%s/%s.secret' "$CONF_DIR" "$1"; }

secret_get() {
  # Tests set CLIENT_PAGE_TEST_SECRETS=1 and override a secret through CLIENT_PAGE_CF_TOKEN or
  # CLIENT_PAGE_ADMIN_TOKEN (set but empty means "not saved"); an unset variable uses the real store.
  if [[ "${CLIENT_PAGE_TEST_SECRETS:-}" == 1 ]]; then
    if [[ "$1" == "$KC_CF" && -n "${CLIENT_PAGE_CF_TOKEN+set}" ]]; then printf '%s' "$CLIENT_PAGE_CF_TOKEN"; return 0; fi
    if [[ "$1" == "$KC_ADMIN" && -n "${CLIENT_PAGE_ADMIN_TOKEN+set}" ]]; then printf '%s' "$CLIENT_PAGE_ADMIN_TOKEN"; return 0; fi
  fi
  if use_keychain; then
    security find-generic-password -a "$KC_ACCOUNT" -s "$1" -w 2>/dev/null || true
  elif [[ -f "$(secret_file "$1")" ]]; then
    cat "$(secret_file "$1")"
  fi
}

# Stores a newly generated secret (only the admin token; the user stores the Cloudflare token).
secret_set_random() {
  if use_keychain; then
    security add-generic-password -a "$KC_ACCOUNT" -s "$1" -w "$(openssl rand -hex 32)" -U
  else
    ( umask 077; mkdir -p "$CONF_DIR"; openssl rand -hex 32 | tr -d '\n' >"$(secret_file "$1")" )
  fi
}

where_secrets() { if use_keychain; then echo "macOS Keychain"; else echo "files in $CONF_DIR (mode 600)"; fi; }

# The command a user runs in their own terminal to save a secret; it prompts, so nothing is echoed.
save_secret_cmd() {
  if use_keychain; then
    echo "security add-generic-password -a $KC_ACCOUNT -s $1 -U -w"
  else
    echo "( umask 077; mkdir -p $CONF_DIR; read -rsp 'Paste token: ' t; echo; printf '%s' \"\$t\" > $(secret_file "$1") )"
  fi
}

# ---------- config ----------

conf_get() { [[ -f "$CONF" ]] && jq -r --arg k "$1" '.[$k] // empty' "$CONF" || true; }
conf_set() {
  mkdir -p "$CONF_DIR"
  local tmp; tmp="$(mktemp)"
  if [[ -f "$CONF" ]]; then jq --arg k "$1" --arg v "$2" '.[$k] = $v' "$CONF" >"$tmp"
  else jq -n --arg k "$1" --arg v "$2" '{($k): $v}' >"$tmp"; fi
  mv "$tmp" "$CONF"; chmod 600 "$CONF"
}
host() { conf_get host; }
require_host() {
  local h; h="$(host)"
  [[ -n "$h" ]] || die "no site set up yet. Run: $0 doctor docs.<your-domain>"
  printf '%s' "$h"
}
# Base URL of the site; CLIENT_PAGE_BASE overrides it (tests point it at a local server).
site() { if [[ -n "${CLIENT_PAGE_BASE:-}" ]]; then printf '%s' "$CLIENT_PAGE_BASE"; else printf 'https://%s' "$(require_host)"; fi; }
worker_name() { local w; w="$(conf_get worker)"; printf '%s' "${w:-$NAME_DEFAULT}"; }
require_conf() { local v; v="$(conf_get "$1")"; [[ -n "$v" ]] || die "missing '$1' in $CONF; run: $0 setup"; printf '%s' "$v"; }

# ---------- Cloudflare API ----------

# Cloudflare REST call that never exits: prints the JSON body; returns 0 only if Cloudflare says success.
cf_try() {
  local method="$1" path="$2"; shift 2
  local tok; tok="$(secret_get "$KC_CF")"
  [[ -n "$tok" ]] || { echo '{"success":false,"errors":[{"code":0,"message":"no token saved"}]}'; return 1; }
  local out
  out="$(printf 'header = "Authorization: Bearer %s"\n' "$tok" | curl -sS -m 30 -K - -X "$method" "$API$path" "$@" 2>/dev/null)" \
    || { echo '{"success":false,"errors":[{"code":0,"message":"could not reach api.cloudflare.com"}]}'; return 1; }
  printf '%s' "$out"
  [[ "$(jq -r '.success // false' <<<"$out" 2>/dev/null)" == "true" ]]
}

# Cloudflare REST call that exits with a readable explanation on failure.
cf() {
  local method="$1" path="$2" out
  [[ -n "$(secret_get "$KC_CF")" ]] || die "no Cloudflare API token saved. Run: $0 doctor"
  if out="$(cf_try "$@")"; then printf '%s' "$out"; return 0; fi
  jq -r '(.errors // []) | map("  Cloudflare: \(.code) \(.message)") | join("\n")' <<<"$out" >&2 2>/dev/null || printf '%s\n' "$out" >&2
  if grep -Eq '"code": ?(10000|9109|10001)[,}]' <<<"$out"; then
    echo "  The token is missing a permission for this step. Run: $0 doctor" >&2
  fi
  die "Cloudflare refused: $method $path"
}

# Admin call to the deployed Worker. $3 is an optional JSON body file.
admin() {
  local method="$1" path="$2" body="${3:-}"
  local tok; tok="$(secret_get "$KC_ADMIN")"
  [[ -n "$tok" ]] || die "no admin token saved; run: $0 setup"
  local args=(-sS -X "$method" "$(site)/_admin$path" -H "content-type: application/json" -w $'\n%{http_code}')
  [[ -n "$body" ]] && args+=(--data-binary "@$body")
  local out code
  out="$(printf 'header = "Authorization: Bearer %s"\n' "$tok" | curl -K - "${args[@]}")" || die "request failed: $method $path (is the site up? $0 doctor)"
  code="${out##*$'\n'}"; out="${out%$'\n'*}"
  if [[ "$code" != 2* ]]; then printf '%s\n' "$out" >&2; die "admin API answered HTTP $code"; fi
  printf '%s\n' "$out"
}

uuid_ok() { [[ "$1" =~ ^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$ ]] || die "not a page id: $1"; }

# Finds the Cloudflare zone that owns HOST by trying each parent name (works for example.co.uk too).
# Prints the zone JSON object; returns 1 if the token can see no matching zone.
find_zone() {
  local name="$1" out
  while [[ "$name" == *.* ]]; do
    if out="$(cf_try GET "/zones?name=$name")" && [[ "$(jq '.result | length' <<<"$out")" -gt 0 ]]; then
      jq -c '.result[0]' <<<"$out"; return 0
    fi
    name="${name#*.}"
  done
  return 1
}

public_ip() { have dig && dig +short "$1" @1.1.1.1 2>/dev/null | grep -E '^[0-9.]+$' | head -1 || true; }
site_live() { # host: 0 if this Worker answers on it (resolved through public DNS, so stale local caches don't matter)
  local ip; ip="$(public_ip "$1")"
  if [[ -n "$ip" ]]; then curl -fsS -m 10 --resolve "$1:443:$ip" "https://$1/_/health" 2>/dev/null | grep -q '"ok":true'
  else curl -fsS -m 10 "https://$1/_/health" 2>/dev/null | grep -q '"ok":true'; fi
}

# Does this machine's admin token open the live Worker on HOST? Prints match | mismatch | missing | down.
admin_match() {
  local h="$1" tok ip url code
  tok="$(secret_get "$KC_ADMIN")"
  [[ -n "$tok" ]] || { echo missing; return 0; }
  url="${CLIENT_PAGE_BASE:-https://$h}/_admin/pages"
  ip=""; [[ -z "${CLIENT_PAGE_BASE:-}" ]] && ip="$(public_ip "$h")"
  if [[ -n "$ip" ]]; then
    code="$(printf 'header = "Authorization: Bearer %s"\n' "$tok" | curl -sS -m 10 -K - --resolve "$h:443:$ip" -o /dev/null -w '%{http_code}' "$url" 2>/dev/null || true)"
  else
    code="$(printf 'header = "Authorization: Bearer %s"\n' "$tok" | curl -sS -m 10 -K - -o /dev/null -w '%{http_code}' "$url" 2>/dev/null || true)"
  fi
  case "$code" in 2*) echo match ;; 401) echo mismatch ;; *) echo down ;; esac
}

# A hostname where this skill's Worker already answers on ACCOUNT (custom domain or workers.dev), if any.
existing_host() {
  local acc="$1" out hn sub
  if out="$(cf_try GET "/accounts/$acc/workers/domains")"; then
    hn="$(jq -r --arg s "$(worker_name)" '[.result[] | select(.service == $s)][0].hostname // empty' <<<"$out")"
    [[ -n "$hn" ]] && { printf '%s' "$hn"; return 0; }
  fi
  if out="$(cf_try GET "/accounts/$acc/workers/scripts/$(worker_name)/subdomain")" \
     && [[ "$(jq -r '.result.enabled' <<<"$out")" == true ]]; then
    sub="$(workers_dev_subdomain "$acc")"
    [[ -n "$sub" ]] && printf '%s' "$(worker_name).$sub.workers.dev"
  fi
  return 0
}

